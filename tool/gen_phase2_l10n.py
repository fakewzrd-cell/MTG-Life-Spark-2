LOCALES = {
    "en": EN,
    "es": ES,
    "pt": PT,
    "pt_BR": PT_BR,
    "fr": FR,
    "de": DE,
    "ja": JA,
}


def main() -> None:
    missing: list[str] = []
    for loc, d in LOCALES.items():
        if loc == "en":
            continue
        for k in EN:
            if k not in d:
                missing.append(f"{loc}:{k}")
        extra = set(d) - set(EN)
        if extra:
            raise SystemExit(f"Extra keys in {loc}: {sorted(extra)[:10]}")
    if missing:
        raise SystemExit(f"Missing {len(missing)} keys, e.g. {missing[:20]}")

    # Placeholder parity (names must match; order may differ for grammar)
    ph = re.compile(r"\{(\w+)\}")
    for loc, d in LOCALES.items():
        for k, v in d.items():
            en_ph = sorted(ph.findall(EN[k]))
            loc_ph = sorted(ph.findall(v))
            if en_ph != loc_ph:
                raise SystemExit(f"Placeholder mismatch {loc}.{k}: {en_ph} vs {loc_ph}")

    out = {"meta": META, **{loc: LOCALES[loc] for loc in ("en", "es", "pt", "pt_BR", "fr", "de", "ja")}}
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"en key count: {len(EN)}")
    print(f"meta count: {len(META)}")
    for loc in ("es", "pt", "pt_BR", "fr", "de", "ja"):
        print(f"{loc} key count: {len(LOCALES[loc])} match={set(LOCALES[loc])==set(EN)}")


if __name__ == "__main__":
    main()
